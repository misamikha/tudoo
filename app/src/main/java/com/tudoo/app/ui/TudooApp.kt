private data class TabItem(
    val route: String,
    val label: String,
    val icon: ImageVector
)

private val tabs = listOf(
    TabItem("home", "Home", Icons.Filled.Home),
    TabItem("tasks", "My Tasks", Icons.Filled.CheckCircle),
    TabItem("settings", "Settings", Icons.Filled.Settings)
)

@Composable
fun TudooApp() {
    val navController = rememberNavController()
    val backStackEntry by navController.currentBackStackEntryAsState()
    val currentRoute = backStackEntry?.destination?.route

    Scaffold(
        containerColor = MaterialTheme.colorScheme.background,
        bottomBar = {
            NavigationBar(containerColor = MaterialTheme.colorScheme.surface) {
                tabs.forEach { tab ->
                    NavigationBarItem(
                        selected = currentRoute == tab.route,
                        onClick = {
                            navController.navigate(tab.route) {
                                popUpTo(navController.graph.findStartDestination().id) {
                                    saveState = true
                                }
                                launchSingleTop = true
                                restoreState = true
                            }
                        },
                        icon = { Icon(tab.icon, contentDescription = tab.label) },
                        label = { Text(tab.label) },
                        colors = NavigationBarItemDefaults.colors(
                            selectedIconColor = MaterialTheme.colorScheme.primary,
                            selectedTextColor = MaterialTheme.colorScheme.primary,
                            indicatorColor = MaterialTheme.colorScheme.secondaryContainer
                        )
                    )
                }
            }
        }
    ) { padding ->
        NavHost(
            navController = navController,
            startDestination = "home",
            modifier = Modifier.padding(padding)
        ) {
            composable("home") {
                DodoScreen(
                    title = "Halo! Aku Dodo",
                    message = "Yuk, selesaikan tugasmu! Aku siap menemanimu.",
                    imageRes = R.drawable.dodo_senang
                )
            }
            composable("tasks") {
                DodoScreen(
                    title = "Belum ada tugas",
                    message = "Santai dulu ya. Tugasmu akan muncul di sini.",
                    imageRes = R.drawable.dodo_tidur
                )
            }
            composable("settings") {
                DodoScreen(
                    title = "Pengaturan",
                    message = "Pengaturan Tudoo akan ada di sini.",
                    imageRes = R.drawable.dodo_bangga
                )
            }
        }
    }
}

@Composable
private fun DodoScreen(
    title: String,
    message: String,
    @DrawableRes imageRes: Int
) {
    Column(
        modifier = Modifier
            .fillMaxSize()
            .padding(32.dp),
        verticalArrangement = Arrangement.Center,
        horizontalAlignment = Alignment.CenterHorizontally
    ) {
        Image(
            painter = painterResource(id = imageRes),
            contentDescription = "Dodo",
            modifier = Modifier.size(180.dp)
        )
        Spacer(modifier = Modifier.height(16.dp))
        Text(
            text = title,
            style = MaterialTheme.typography.headlineMedium,
            color = MaterialTheme.colorScheme.primary,
            textAlign = TextAlign.Center
        )
        Text(
            text = message,
            style = MaterialTheme.typography.bodyLarge,
            color = MaterialTheme.colorScheme.onBackground,
            textAlign = TextAlign.Center,
            modifier = Modifier.padding(top = 8.dp)
        )
    }
}
